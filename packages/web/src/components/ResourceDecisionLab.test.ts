// @vitest-environment happy-dom
import { mount } from '@vue/test-utils';
import { describe, expect, it } from 'vitest';
import ResourceDecisionLab from './ResourceDecisionLab.vue';
const lab={work_gflops:600,read_gb:16,compute_tflops:60,bandwidth_tb_s:2,target_ms:9};
const experiment={kind:'resource_bounds' as const,instruction:'比较两项时间',work_gflops:140,read_gb:70,compute_tflops:989.4,bandwidth_tb_s:3.35};
describe('linked resource decision experiment',()=>{
  it('changes batch size using shared reads and total work, and connects an object question to its current values',async()=>{
    const batch={work_gflops:140,read_gb:70,compute_tflops:989.4,bandwidth_tb_s:3.35,target_ms:9,batch_size:1};
    const w=mount(ResourceDecisionLab,{props:{lab:batch,experiment:{...experiment,batch_size:1},saved:null,observed:[],disabled:false}});
    await w.findAll('button').find(b=>b.text()==='8 条请求')!.trigger('click');
    expect(w.emitted('observe')?.[0]).toEqual(['batch_eight']);
    expect(w.emitted('change')?.at(-1)?.[0]).toMatchObject({batch_size:8,work_gflops:1120,read_gb:70});
    expect(w.get('.batch-readouts').text()).toContain('2.61');expect(w.get('.batch-readouts').text()).toContain('382.9');
    await w.findAll('.object-tabs button').find(b=>b.text()==='计算阵列')!.trigger('click');
    expect(w.get('.object-values').text()).toContain('1120 GFLOPs');
    await w.get('.ask-object').trigger('click');expect(w.emitted('question')?.[0]?.[0]).toContain('计算阵列');
    expect(w.emitted('question')?.[0]?.[0]).toContain('1120 GFLOPs');
    await w.get('input[aria-label="本批请求数"]').setValue('4');
    expect(w.emitted('change')?.at(-1)?.[0]).toMatchObject({batch_size:4,work_gflops:560,read_gb:70});
    await w.findAll('button').find(b=>b.text()==='保存这个实验配置')!.trigger('click');
    expect(w.emitted('save')?.[0]).toEqual([{...batch,batch_size:4,work_gflops:560}]);
    await w.get('input[aria-label="本批请求数"]').setValue('64');
    await w.findAll('button').find(b=>b.text()==='当前计算量 ×2')!.trigger('click');
    expect(w.emitted('change')?.at(-1)?.[0]).toMatchObject({batch_size:64,work_gflops:17920,read_gb:70});
    w.unmount();
  });
  it('exposes the bottleneck switch, workload reversal and exact saved conditions',async()=>{
    const w=mount(ResourceDecisionLab,{props:{lab,experiment,saved:null,observed:[],disabled:false}});
    const button=(label:string)=>w.findAll('button').find(b=>b.text()===label)!;
    await button('恢复本轮实验起点').trigger('click');
    expect(w.find('.bound').text()).toContain('10.00');
    await button('当前算力 ×2').trigger('click');
    expect(w.find('.bound').text()).toContain('8.00');
    expect(w.find('.target-result').text()).toContain('需要实测');
    expect(w.find('[role="img"]').attributes('aria-label')).toContain('计算 5.00 ms，读取 8.00 ms');
    await button('当前计算量 ×2').trigger('click');
    expect(w.find('.bound').text()).toContain('10.00');
    expect(w.find('.target-result').text()).toContain('直接排除');
    expect(w.emitted('save')).toBeUndefined();
    await button('保存这个实验配置').trigger('click');
    expect(w.emitted('save')?.[0]).toEqual([{...lab,compute_tflops:120,work_gflops:1200}]);
    w.unmount();
  });
  it('rotates real projected geometry without changing resource calculations and restores a saved experiment',async()=>{
    const saved={...lab,compute_tflops:120};
    const w=mount(ResourceDecisionLab,{props:{lab,experiment,saved,observed:['baseline','double_compute','double_bandwidth'],disabled:false}});
    const before=w.find('.surface polygon').attributes('points');
    const values=w.find('.readouts').text();
    await w.find('.surface').trigger('keydown',{key:'ArrowRight'});
    expect(w.find('.surface polygon').attributes('points')).not.toBe(before);
    expect(w.find('.readouts').text()).toBe(values);
    expect(w.find('.save').attributes('disabled')).toBeDefined();
    expect(w.find('.readouts').text()).toContain('8.00');
    w.unmount();
  });
  it('lets the learner locate the exact switch and design a larger workload using numeric controls',async()=>{
    const w=mount(ResourceDecisionLab,{props:{lab,experiment:{...experiment,...lab},saved:null,observed:[],disabled:false}});
    await w.get('#course-value-compute_tflops').setValue('75');
    expect(w.get('.bound').text()).toContain('8.00');
    expect(w.get('.bound').text()).toContain('两项相等');
    await w.get('#course-value-work_gflops').setValue('1440');
    await w.get('#course-value-read_gb').setValue('48');
    await w.get('#course-value-compute_tflops').setValue('200');
    await w.get('#course-value-bandwidth_tb_s').setValue('6');
    expect(w.get('.readouts').text()).toContain('7.20');
    expect(w.get('.bound').text()).toContain('8.00');
    expect(w.emitted('change')?.at(-1)?.[0]).toMatchObject({work_gflops:1440,read_gb:48,compute_tflops:200,bandwidth_tb_s:6});
    await w.get('#course-value-bandwidth_tb_s').setValue('5');
    await w.findAll('button').find(b=>b.text()==='当前带宽 ×2')!.trigger('click');
    expect(w.emitted('change')?.at(-1)?.[0]).toMatchObject({bandwidth_tb_s:10});
    await w.get('#course-value-bandwidth_tb_s').setValue('6');
    await w.get('#course-value-target_ms').setValue('6');
    expect(w.get('.target-result').text()).toContain('直接排除');
    await w.get('#course-value-compute_tflops').setValue('0');
    expect((w.get('#course-value-compute_tflops').element as HTMLInputElement).value).toBe('200');
    expect(w.get('.readouts').text()).not.toContain('Infinity');
    w.unmount();
  });
});
