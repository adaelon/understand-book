async function get(path, request = context.request) {
  const response = await request.get(base + path); assert.equal(response.status(), 200, path); return response.json();
}
async function adminPost(path, data) {
  const identity = await get('/api/auth/me', admin.request);
  const response = await admin.request.post(base + path, { headers: { Origin: base, 'X-CSRF-Token': identity.csrf_token }, data });
  assert.equal(response.status(), 200, await response.text()); return response.json();
}
