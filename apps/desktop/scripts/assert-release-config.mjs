import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const origin = process.env.UNDERSTAND_BOOK_CLOUD_ORIGIN?.trim();
assert(origin, 'Set UNDERSTAND_BOOK_CLOUD_ORIGIN to the deployed HTTPS Reader origin before packaging.');
const url = new URL(origin);
assert(url.protocol === 'https:' && url.pathname === '/' && !url.search && !url.hash && !url.username && !url.password,
  'UNDERSTAND_BOOK_CLOUD_ORIGIN must be an HTTPS origin without path, query or credentials.');
const config = JSON.parse(readFileSync(path.join(root, 'src-tauri/tauri.conf.json'), 'utf8'));
assert(!(config.bundle.externalBin?.length), 'Cloud Setup must not include local execution binaries.');
assert(!(config.bundle.resources?.length), 'Cloud Setup must not include local processing resources.');
assert.equal(config.build.frontendDist, '../local-reader');
assert(config.build.beforeBuildCommand.includes('build-local-reader.mjs'), 'Bundle the offline local library.');
assert(!/sidecar|video-resources|book-mcp|web build/.test(config.build.beforeBuildCommand), 'Cloud build must not build the local execution chain.');
const cargo = readFileSync(path.join(root, 'src-tauri/Cargo.toml'), 'utf8');
assert(!/^\s*(server|runtime)\s*=/m.test(cargo), 'Desktop must not depend on server/runtime.');
const hooks = readFileSync(path.join(root, 'src-tauri/windows/installer-hooks.nsh'), 'utf8');
assert(!/--install-codex-plugin|--uninstall-owned-codex-plugin|ExecWait/.test(hooks), 'Setup must not install or remove user plugins.');
console.log(`Cloud release configuration ready: ${url.origin}`);
