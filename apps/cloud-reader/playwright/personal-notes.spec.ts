test('an original material scene opens from a note and accepts the standalone discussion',async({page,request})=>{
  await page.setViewportSize({width:1440,height:1000});
  const seed=await request.get('http://127.0.0.1:4231/fixture').then(response=>response.json());
  await page.evaluate(async publication=>{
    const path='/reader-src/personal-notes';const notes=await import(path);
    const value=notes.emptyNoteContent({book_id:publication.book_id,publication_id:publication.publication_id,lid:'1.1',label:'记录时的原资料'},'参数固定，表示随输入而变。回到当时的材料继续检查。');
    value.title='回到原资料的想法';
    await notes.noteRequest('create',{operation_id:crypto.randomUUID(),value});
  },seed.publication);
  await page.getByRole('button',{name:/^我的想法/}).click();
  const notes=page.getByRole('region',{name:'我的想法',exact:true});
  await notes.locator('.note-list').getByRole('button',{name:/回到原资料的想法/}).click();
  await notes.getByRole('button',{name:/回到记录现场/}).click();
  await expect(notes).toBeHidden({timeout:25_000});
  const material=await page.evaluate(async()=>{const path='/src/network-context.ts';return (await import(path)).network.value.workspace;});
  expect(material.published_book_ref).toEqual(seed.publication);
  await page.getByRole('button',{name:/^我的想法/}).click();
  await notes.locator('.note-list').getByRole('button',{name:/回到原资料的想法/}).click();
  await notes.getByRole('button',{name:/一起推敲/}).click();
  const chat=page.getByRole('dialog',{name:'推敲我的想法',exact:true});
  await chat.getByRole('textbox',{name:'讨论我的想法',exact:true}).fill('这组参数固定，我还想检查输入与输出的关系。');
  await chat.getByRole('button',{name:'发送',exact:true}).click();
  await expect(chat.locator('.chat-answer')).toContainText('激活还依赖这次输入',{timeout:25_000});
  await chat.getByRole('textbox',{name:'讨论我的想法',exact:true}).fill('请结合刚才打开的资料继续检查这个想法。');
  const admitted=page.waitForResponse(response=>response.url().endsWith('/agent/runs') && response.request().method()==='POST');
  await chat.getByRole('button',{name:'在当前打开的资料中继续',exact:true}).click();
  const response=await admitted;
  expect(response.ok()).toBe(true);
  const payload=response.request().postDataJSON();
  expect(payload.personal_chat_ref.session_id).toBeTruthy();expect(payload.personal_chat_ref.turn_id).toBeTruthy();
  await expect(chat).toBeHidden();
  await expect(page.locator('#reader-panel-agent .answer-markdown').filter({hasText:'激活还依赖这次输入'})).toBeVisible({timeout:25_000});
  await page.screenshot({path:resolve(output,'discussion-into-material.png'),fullPage:true});
  writeFileSync(resolve(output,'source-navigation.json'),JSON.stringify({publication:material.published_book_ref,accepted:response.status(),personal_chat_ref:payload.personal_chat_ref,note_refs:payload.note_refs},null,2));
});
